#!/usr/bin/env python3
"""Inline the art sources (art/*.js) into index.html between the ART markers.
The game stays one file; the art stays editable as separate sources. Run after editing anything in art/."""
import os,re
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER=['engine','fx','dragon','beast','crab','arthro','serpent','serp2','raptor','bird','snap','icons','wpn','sig','hunter']
body='\n'.join(open(os.path.join(ROOT,'art',f+'.js')).read().rstrip('\n') for f in ORDER)
block=('// ART:BEGIN (generated by tools/build-art.py from art/*.js, edit those, not this)\n'
       'const ART=(()=>{\n'+body+'\nreturn{ENG,KIT,MON,ICON,WPN,SIG,HUN};\n})();\n// ART:END')
p=os.path.join(ROOT,'index.html');s=open(p).read()
if '// ART:BEGIN' in s: s=re.sub(r'// ART:BEGIN.*?// ART:END',lambda m:block,s,flags=re.S)
else:
    a='// ═══════════════════════════════════════════════════\n//  PIXEL SPRITES'
    assert a in s; s=s.replace(a,block+'\n\n'+a,1)
open(p,'w').write(s);print('art inlined:',len(block)//1024,'KB')
